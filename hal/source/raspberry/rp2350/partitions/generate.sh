#!/bin/bash
# Regenerate the RP2350 partition table from partition_table.json with picotool.
#
#   hal/source/raspberry/rp2350/partitions/generate.sh [PICOTOOL]
#
# Writes two files from one picotool run:
#   partition_table.zig  the table as words, linked into the kernel ELF
#                        (section .partition_table: run 0x1c000000, load
#                        0x10000000), so programming the kernel writes it
#   partition_table.bin  the same 124-odd bytes on their own, for picotool or
#                        a UF2 (scripts/make_uf2.py)
#
# The layout (partition_table.json):
#   0x000000  4 KB      this table (slot 0)
#   0x001000  4 KB      free: slot 1, where the bootrom looks for a newer copy
#   0x002000  120 KB    partition 0 "yasboot": the bootloader, tried first
#   0x020000  16252 KB  partition 1 "yasos": the kernel, then the romfs
#   0xFFF000  4 KB      unpartitioned: RP2350-E10's UF2 workaround block
#
# The bootrom boots the first partition holding a valid IMAGE_DEF -- while
# partition 0 is erased, the kernel -- and maps it at 0x10000000 (QMI ATRANS):
# the kernel stays linked at 0x10000000 and is loaded 0x20000 higher (the
# rp2350 linker scripts' flash_load), the romfs at virtual 0x10100000 is flash
# offset 0x120000.
#
# PICOTOOL defaults to `picotool` from PATH.  Without one, build it for the
# PC from the copy in the tree (no USB needed):
#   cmake -S hal/source/raspberry/rp2350/pico_sdk_generated/_deps/picotool-src \
#         -B /tmp/picotool -DPICO_SDK_PATH=$PWD/hal/libs/pico-sdk -DPICOTOOL_NO_LIBUSB=1
#   make -C /tmp/picotool picotool
set -euo pipefail
HERE=$(cd "$(dirname "$0")" && pwd)
PICOTOOL=${1:-picotool}
"$PICOTOOL" partition create --quiet --no-btstack-flash-bank \
    "$HERE/partition_table.json" "$HERE/partition_table.bin"
"$PICOTOOL" info -a "$HERE/partition_table.bin" | sed -n '/Program Information/,/hash:/p'
python3 - "$HERE/partition_table.bin" "$HERE/partition_table.zig" <<'PY'
import struct, sys
data = open(sys.argv[1], "rb").read()
assert len(data) % 4 == 0 and data[:4] == b"\xd3\xde\xff\xff", "not a picobin block"
words = struct.unpack(f"<{len(data) // 4}I", data)
rows = "\n".join("        " + ", ".join(f"0x{w:08x}" for w in words[i:i + 4]) + ","
                 for i in range(0, len(words), 4))
open(sys.argv[2], "w").write(f"""//! The RP2350 partition table (generated by generate.sh from
//! partition_table.json -- edit the JSON and regenerate, not this file).
//!
//! Linked into the kernel ELF in .partition_table, which the rp2350 linker
//! scripts place at run address 0x1c000000 (the untranslated XIP alias, i.e.
//! flash offset 0 as the CPU can read it) and load address 0x10000000 (flash
//! offset 0): programming the kernel ELF writes the table into sector 0.
//! The layout and why the kernel can stay linked at 0x10000000 are in
//! generate.sh.  {len(data)} bytes, picotool `partition create`, with a
//! SHA-256 hash the bootrom checks.

comptime {{
    _ = PartitionTable.partition_table;
}}

const PartitionTable = struct {{
    export const partition_table: [{len(words)}]u32 linksection(".partition_table") = .{{
{rows}
    }};
}};
""")
PY
echo "wrote $HERE/partition_table.bin and $HERE/partition_table.zig"
